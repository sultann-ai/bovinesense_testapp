-- BovineSense — initial schema.
--
-- Ported from the Drizzle schema (db/schema.ts + drizzle/0000, 0001). Differences
-- from the Drizzle version are deliberate and listed here:
--   * timestamps are timestamptz (PostgREST returns them with an offset, so
--     browsers do not parse them as local time);
--   * fixes.lat / fixes.lon are double precision (were real) and fixes.geom is a
--     generated point derived from them, so inserts through the Data API cannot
--     put lat/lon and geom out of sync;
--   * at most one active fence per animal is now enforced (DESIGN.md §7);
--   * district_boundaries.gadm_gid is unique so the boundary import is re-runnable;
--   * a few FK/status indexes were added.
--
-- Tenancy (organization_id) and Auth are NOT part of this migration.
--
-- Every table has Row Level Security enabled and NO policies yet, so the Data
-- API roles (anon, authenticated) can read nothing. The app reads through the
-- server-only service-role client until the auth/tenancy module adds policies.

create extension if not exists postgis with schema extensions;

-- ─── Enums ───────────────────────────────────────────────────────────────────
create type public.user_role as enum (
  'hq_admin', 'regional_manager', 'branch_officer', 'auditor'
);
create type public.fence_type as enum ('district', 'polygon', 'radius');
create type public.alert_type as enum (
  'breach', 'near_boundary', 'fast_movement', 'tag_offline', 'low_battery', 'returned'
);
create type public.alert_severity as enum ('critical', 'warning', 'info');
create type public.alert_status as enum ('new', 'acknowledged', 'assigned', 'resolved');
create type public.resolution_reason as enum (
  'returned_home', 'false_alarm', 'moved_with_bank_consent', 'escalated_to_recovery'
);
create type public.animal_status as enum ('inside', 'near', 'breach', 'fast', 'stale');

-- ─── Organisational hierarchy ────────────────────────────────────────────────
create table public.regions (
  id    integer generated by default as identity primary key,
  name  varchar(100) not null unique,
  code  varchar(20)  not null unique
);

create table public.branches (
  id         integer generated by default as identity primary key,
  name       varchar(100) not null,
  code       varchar(20)  not null unique,
  region_id  integer      not null references public.regions (id),
  district   varchar(100)
);

create table public.users (
  id          integer generated by default as identity primary key,
  name        varchar(150) not null,
  email       varchar(150) not null unique,
  role        public.user_role not null default 'branch_officer',
  branch_id   integer references public.branches (id),
  region_id   integer references public.regions (id),
  created_at  timestamptz  not null default now()
);

-- ─── Borrowers and loans ─────────────────────────────────────────────────────
create table public.borrowers (
  id          integer generated by default as identity primary key,
  name        varchar(150) not null,
  cnic        varchar(15) unique,
  phone       varchar(20),
  address     text,
  district    varchar(100),
  branch_id   integer      not null references public.branches (id),
  created_at  timestamptz  not null default now()
);

create table public.loans (
  id           integer generated by default as identity primary key,
  loan_number  varchar(50) not null unique,
  borrower_id  integer     not null references public.borrowers (id),
  branch_id    integer     not null references public.branches (id),
  amount_pkr   integer     not null,
  disbursed_at timestamptz,
  status       varchar(20) not null default 'active'
);

-- ─── Geography ───────────────────────────────────────────────────────────────
create table public.district_boundaries (
  id             integer generated by default as identity primary key,
  district_name  varchar(150) not null,
  province       varchar(100),
  gadm_gid       varchar(50),
  geom           extensions.geometry(Geometry, 4326) not null
);
create index district_boundaries_geom_idx on public.district_boundaries using gist (geom);
create unique index district_boundaries_gadm_gid_key on public.district_boundaries (gadm_gid);

create table public.geofences (
  id                integer generated by default as identity primary key,
  name              varchar(150) not null,
  type              public.fence_type not null,
  geom              extensions.geometry(Geometry, 4326) not null,
  warning_buffer_m  integer not null default 500,
  district_name     varchar(150),
  created_at        timestamptz not null default now()
);
create index geofences_geom_idx on public.geofences using gist (geom);

-- ─── Tags and animals ────────────────────────────────────────────────────────
create table public.tags (
  id             integer generated by default as identity primary key,
  serial_number  varchar(50) not null unique,
  is_simulated   boolean     not null default false,
  last_seen_at   timestamptz
);

create table public.animals (
  id           integer generated by default as identity primary key,
  name         varchar(100),
  species      varchar(50) not null default 'cattle',
  sex          varchar(10),
  age_years    real,
  tag_id       integer references public.tags (id),
  borrower_id  integer not null references public.borrowers (id),
  loan_id      integer references public.loans (id),
  branch_id    integer not null references public.branches (id),
  district     varchar(100),
  status       public.animal_status not null default 'inside',
  created_at   timestamptz not null default now()
);
create index animals_tag_idx    on public.animals (tag_id);
create index animals_branch_idx on public.animals (branch_id);

create table public.animal_geofence (
  id           integer generated by default as identity primary key,
  animal_id    integer not null references public.animals (id),
  geofence_id  integer not null references public.geofences (id),
  assigned_at  timestamptz not null default now(),
  is_active    boolean not null default true
);
create index animal_geofence_animal_idx on public.animal_geofence (animal_id);
create index animal_geofence_fence_idx  on public.animal_geofence (geofence_id);
-- One active fence per animal (DESIGN.md §7).
create unique index animal_geofence_one_active_idx
  on public.animal_geofence (animal_id) where is_active;

-- ─── Fixes ───────────────────────────────────────────────────────────────────
create table public.fixes (
  id           integer generated by default as identity primary key,
  tag_id       integer not null references public.tags (id),
  animal_id    integer references public.animals (id),
  lat          double precision not null,
  lon          double precision not null,
  geom         extensions.geometry(Point, 4326)
                 generated always as (
                   extensions.st_setsrid(extensions.st_makepoint(lon, lat), 4326)
                 ) stored,
  fixed_at     timestamptz not null,
  speed_kmh    real,
  battery_pct  integer,
  signal_bars  integer,
  is_simulated boolean not null default false,
  created_at   timestamptz not null default now()
);
create index fixes_geom_idx        on public.fixes using gist (geom);
create index fixes_tag_time_idx    on public.fixes (tag_id, fixed_at);
create index fixes_animal_time_idx on public.fixes (animal_id, fixed_at);

-- ─── Alerts ──────────────────────────────────────────────────────────────────
create table public.alerts (
  id                 integer generated by default as identity primary key,
  animal_id          integer not null references public.animals (id),
  tag_id             integer references public.tags (id),
  type               public.alert_type     not null,
  severity           public.alert_severity not null,
  status             public.alert_status   not null default 'new',
  title              varchar(255) not null,
  detail             text,
  distance_km        real,
  assignee_id        integer references public.users (id),
  created_at         timestamptz not null default now(),
  acknowledged_at    timestamptz,
  assigned_at        timestamptz,
  resolved_at        timestamptz,
  resolution_reason  public.resolution_reason,
  resolution_note    text
);
create index alerts_animal_idx         on public.alerts (animal_id);
create index alerts_status_created_idx on public.alerts (status, created_at desc);

create table public.alert_events (
  id           integer generated by default as identity primary key,
  alert_id     integer not null references public.alerts (id),
  from_status  public.alert_status,
  to_status    public.alert_status not null,
  user_id      integer references public.users (id),
  note         text,
  created_at   timestamptz not null default now()
);
create index alert_events_alert_idx on public.alert_events (alert_id);

-- ─── Row Level Security: enabled everywhere, no policies yet ─────────────────
alter table public.regions             enable row level security;
alter table public.branches            enable row level security;
alter table public.users               enable row level security;
alter table public.borrowers           enable row level security;
alter table public.loans               enable row level security;
alter table public.district_boundaries enable row level security;
alter table public.geofences           enable row level security;
alter table public.tags                enable row level security;
alter table public.animals             enable row level security;
alter table public.animal_geofence     enable row level security;
alter table public.fixes               enable row level security;
alter table public.alerts              enable row level security;
alter table public.alert_events        enable row level security;
